#!/usr/bin/env python3
"""Generate compact antialiased 24x32 font cells for STATION from Pillow's bundled
open-source default scalable font (no runtime dependencies on the PS3)."""
from PIL import Image, ImageDraw, ImageFont
from pathlib import Path

CELL_W, CELL_H = 24, 32
font = ImageFont.load_default(size=23)
data = []
widths = []
for code in range(32, 128):
    char = chr(code)
    img = Image.new("L", (CELL_W, CELL_H), 0)
    draw = ImageDraw.Draw(img)
    draw.text((1, -2), char, font=font, fill=255)
    data.extend(img.tobytes())
    widths.append(min(23, max(6, round(font.getlength(char)) + 1)))
target = Path("source/ui_font_generated.h")
with target.open("w") as f:
    f.write("/* generated by assets/gen_font.py; font pixels are premultiplied at runtime */\n")
    f.write("#ifndef STATION_UI_FONT_GENERATED_H\n#define STATION_UI_FONT_GENERATED_H\n")
    f.write("static const unsigned char station_font_width[96] = {\n")
    for x in range(0, 96, 16):
        f.write(" " + ",".join(map(str, widths[x:x+16])) + ",\n")
    f.write("};\nstatic const unsigned char station_font_alpha[96*24*32] = {\n")
    for x in range(0, len(data), 32):
        f.write(" " + ",".join(map(str, data[x:x+32])) + ",\n")
    f.write("};\n#endif\n")
print("Generated", target, len(data), "alpha bytes")
