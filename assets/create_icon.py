def lettering(x, y, message, scale, color, tracking=1):
    for char in message.upper():
        rows = FONT.get(char, FONT[" "])
        for yy, bits in enumerate(rows):
            for xx, bit in enumerate(bits):
                if bit == "1":
                    rectangle(x + xx * scale, y + yy * scale, scale, scale, color)
        x += (5 + tracking) * scale

for y in range(H):
    for x in range(W):
        t = (y / H) * .6 + (x / W) * .35
        glow = max(0., 1. - math.hypot((x - 304) / 205, (y - 48) / 180))
        pixel(x, y, (int(8 + 12 * t + 6 * glow),
                     int(15 + 20 * t + 9 * glow),
                     int(32 + 26 * t + 15 * glow)))
rectangle(0, 0, W, 4, (47, 155, 252))
rectangle(18, 19, 3, 22, (65, 166, 250))
lettering(29, 22, "YOUR LIBRARY", 2, (151, 182, 217))
